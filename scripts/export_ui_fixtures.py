"""Export real API responses for frontend tests (frontend/src/test/fixtures/).

Run from the backend environment:  ``cd backend && uv run python ../scripts/export_ui_fixtures.py``
Re-run whenever rules, correlation or the finding schema change, so UI tests use the real
API shape. Uses a throwaway database; no network.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from fastapi.testclient import TestClient  # noqa: E402
from pydantic import SecretStr  # noqa: E402

from app.core.config import Settings  # noqa: E402
from app.main import create_app  # noqa: E402
from app.runtime.recording import loads  # noqa: E402
from app.runtime.scanner import run_runtime_rules  # noqa: E402
from app.storage.repositories import ScanRepository  # noqa: E402

OUT = ROOT / "frontend" / "src" / "test" / "fixtures"
TOKEN = "f" * 48
STABLE = "Generated by Magen 0.1.0 (fixture)"


def read(rel: str) -> str:
    return (ROOT / "corpus" / rel).read_text(encoding="utf-8")


def stable(data: Any) -> Any:
    """Replace volatile fields so fixtures do not churn between runs."""
    if isinstance(data, dict):
        out = {}
        for k, v in data.items():
            if k == "generated_by":
                out[k] = STABLE
            elif k in ("created_at", "started_at", "finished_at", "authorized_at"):
                out[k] = "2026-11-22T10:00:00+00:00"
            else:
                out[k] = stable(v)
        return out
    if isinstance(data, list):
        return [stable(v) for v in data]
    return data


def write(name: str, data: Any) -> None:
    text = json.dumps(stable(data), indent=2, ensure_ascii=False) + "\n"
    (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {name}\n")


def main() -> None:
    """Drive the real API against a temporary database."""
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(session_token=SecretStr(TOKEN), data_dir=Path(tmp))
        with TestClient(create_app(settings), headers={"X-Magen-Token": TOKEN}) as c:
            for name, kind, rel in [
                ("openapi-no-auth.json", "openapi", "openapi/no-auth.yaml"),
                ("nginx-legacy-tls.json", "nginx", "nginx/legacy-tls.conf"),
                ("nginx-site-snippet.json", "nginx", "nginx/site-snippet.conf"),
            ]:
                body = {"filename": Path(rel).name, "content": read(rel)}
                write(name, c.post(f"/api/analyze/{kind}", json=body).json())

            def session(**body: Any) -> dict[str, Any]:
                res = c.post("/api/sessions", json=body)
                res.raise_for_status()
                return dict(res.json())

            def inp(kind: str, rel: str, content: str | None = None) -> dict[str, str]:
                return {"kind": kind, "filename": Path(rel).name, "content": content or read(rel)}

            write(
                "session-mixed.json",
                session(
                    inputs=[
                        inp("openapi", "openapi/no-auth.yaml"),
                        inp("nginx", "nginx/legacy-tls.conf"),
                    ]
                ),
            )
            write("session-snippet.json", session(inputs=[inp("nginx", "nginx/site-snippet.conf")]))

            repo = ScanRepository(c.app.state.db)  # type: ignore[attr-defined]
            target = c.post(
                "/api/targets", json={"host": "legacy.example.com", "authorization_confirmed": True}
            ).json()
            recording = read("runtime/legacy-server.json")
            scan_id = repo.create(
                target_id=target["id"],
                options={"kind": "runtime", "base_url": "https://legacy.example.com/"},
                version="0.1.0",
                commit="fixture",
            )
            repo.finish(
                scan_id, "done", run_runtime_rules(loads(recording)), observations=recording
            )
            write(
                "session-correlated.json",
                session(inputs=[inp("nginx", "nginx/legacy-tls.conf")], runtime_scan_id=scan_id),
            )

            base = session(inputs=[inp("nginx", "nginx/legacy-tls.conf")])
            partly_fixed = read("nginx/legacy-tls.conf").replace(
                "SSLv3 TLSv1 TLSv1.2", "TLSv1.2 TLSv1.3"
            )
            write(
                "session-retest.json",
                session(
                    inputs=[inp("nginx", "nginx/legacy-tls.conf", partly_fixed)],
                    baseline_id=base["id"],
                ),
            )
            write("sessions.json", c.get("/api/sessions").json())

            for name, kind, rel in [
                ("remediation-legacy.json", "nginx", "nginx/legacy-tls.conf"),
                ("remediation-cors.json", "nginx", "nginx/cors.conf"),
            ]:
                body = {"kind": kind, "filename": Path(rel).name, "content": read(rel)}
                write(name, c.post("/api/remediation/preview", json=body).json())


if __name__ == "__main__":
    main()
