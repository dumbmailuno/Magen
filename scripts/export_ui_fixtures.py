"""Export real analyzer output for frontend tests (frontend/src/test/fixtures/).

Run from the backend environment:  ``cd backend && uv run python ../scripts/export_ui_fixtures.py``
Re-run whenever rules or the finding schema change, so UI tests use the real API shape.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.api.analyze import (  # noqa: E402
    NginxInput,
    OpenApiInput,
    analyze_nginx_endpoint,
    analyze_openapi_endpoint,
)

OUT = ROOT / "frontend" / "src" / "test" / "fixtures"
CASES = {
    "openapi-no-auth.json": ("openapi", "corpus/openapi/no-auth.yaml"),
    "nginx-legacy-tls.json": ("nginx", "corpus/nginx/legacy-tls.conf"),
    "nginx-site-snippet.json": ("nginx", "corpus/nginx/site-snippet.conf"),
}


def main() -> None:
    """Write one JSON response per case, with a fixed provenance line."""
    OUT.mkdir(parents=True, exist_ok=True)
    for out_name, (kind, rel) in CASES.items():
        text = (ROOT / rel).read_text(encoding="utf-8")
        name = Path(rel).name
        if kind == "openapi":
            result = analyze_openapi_endpoint(OpenApiInput(filename=name, content=text))
        else:
            result = analyze_nginx_endpoint(NginxInput(filename=name, content=text))
        data = result.model_dump(mode="json")
        data["generated_by"] = "Generated by Magen 0.1.0 (fixture)"  # stable across commits
        (OUT / out_name).write_text(
            json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
        )
        sys.stdout.write(f"wrote {out_name}: {len(data['findings'])} findings\n")


if __name__ == "__main__":
    main()
