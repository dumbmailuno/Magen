"""Application settings, loaded from environment variables prefixed ``MAGEN_``."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Final

from pydantic import Field, SecretStr, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

#: The backend only ever binds to loopback (CLAUDE.md §3, §11). Not configurable.
BIND_HOST: Final = "127.0.0.1"


def _default_data_dir() -> Path:
    return Path.home() / ".magen"


class Settings(BaseSettings):
    """Runtime configuration. Secrets are ``SecretStr`` so they never render in logs/reprs."""

    model_config = SettingsConfigDict(env_prefix="MAGEN_", extra="ignore")

    port: int = Field(default=8000, ge=1, le=65535)
    #: Per-session token generated by Electron; every request must send it.
    session_token: SecretStr = Field(min_length=32)
    data_dir: Path = Field(default_factory=_default_data_dir)
    #: Origins allowed to call the API (Vite dev server, Electron's app:// scheme).
    allowed_origins: list[str] = Field(
        default_factory=lambda: ["http://localhost:5173", "http://127.0.0.1:5173", "app://magen"]
    )
    log_level: str = "INFO"
    ollama_url: str = "http://127.0.0.1:11434"
    ollama_model: str = "qwen3:4b"

    @field_validator("ollama_url")
    @classmethod
    def _ollama_must_be_local(cls, value: str) -> str:
        """Cloud AI is out of scope by default (CLAUDE.md §8): only loopback Ollama URLs."""
        allowed = ("http://127.0.0.1", "http://localhost", "http://[::1]")
        if not value.startswith(allowed):
            raise ValueError("ollama_url must point to a loopback address")
        return value

    @property
    def db_path(self) -> Path:
        """Location of the SQLite database file."""
        return self.data_dir / "magen.db"


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    """Return process-wide settings (cached)."""
    return Settings()  # required values (session_token) come from the environment
