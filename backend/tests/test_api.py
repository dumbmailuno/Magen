from __future__ import annotations

from fastapi.testclient import TestClient
from pydantic import SecretStr

from app.core.config import Settings
from app.main import create_app


def test_health(client: TestClient) -> None:
    res = client.get("/api/health")
    assert res.status_code == 200
    body = res.json()
    assert body["status"] == "ok"
    assert body["generated_by"].startswith("Generated by Magen ")


def test_rules_endpoint(client: TestClient) -> None:
    res = client.get("/api/rules")
    assert res.status_code == 200
    assert isinstance(res.json(), list)


def test_token_required(anon_client: TestClient) -> None:
    res = anon_client.get("/api/health")
    assert res.status_code == 401
    assert res.json() == {
        "code": "unauthorized",
        "message": "Missing or invalid session token",
        "detail": None,
    }


def test_wrong_token_rejected(anon_client: TestClient) -> None:
    res = anon_client.get("/api/health", headers={"X-Magen-Token": "x" * 48})
    assert res.status_code == 401


def test_cors_preflight_works_without_token(anon_client: TestClient) -> None:
    res = anon_client.options(
        "/api/health",
        headers={
            "Origin": "http://localhost:5173",
            "Access-Control-Request-Method": "GET",
            "Access-Control-Request-Headers": "x-magen-token",
        },
    )
    assert res.status_code == 200
    assert res.headers["access-control-allow-origin"] == "http://localhost:5173"


def test_foreign_origin_not_allowed(anon_client: TestClient) -> None:
    res = anon_client.options(
        "/api/health",
        headers={"Origin": "https://evil.example", "Access-Control-Request-Method": "GET"},
    )
    assert "access-control-allow-origin" not in res.headers


def test_untrusted_host_header_rejected(client: TestClient) -> None:
    res = client.get("/api/health", headers={"Host": "attacker.example"})
    assert res.status_code == 400


def test_unknown_route_uses_error_shape(client: TestClient) -> None:
    res = client.get("/api/nope")
    assert res.status_code == 404
    assert set(res.json()) == {"code", "message", "detail"}


def test_docs_not_exposed(client: TestClient) -> None:
    assert client.get("/docs").status_code == 404
    assert client.get("/openapi.json").status_code == 404


def test_short_token_rejected_by_settings() -> None:
    import pytest
    from pydantic import ValidationError

    with pytest.raises(ValidationError):
        Settings(session_token=SecretStr("short"))


def test_remote_ollama_rejected() -> None:
    import pytest
    from pydantic import ValidationError

    with pytest.raises(ValidationError):
        Settings(session_token=SecretStr("t" * 48), ollama_url="https://cloud.example")


def test_app_factory_migrates_db(settings: Settings) -> None:
    with TestClient(create_app(settings), headers={"X-Magen-Token": "t" * 48}):
        assert settings.db_path.exists()


SPEC = """openapi: 3.0.3
info: {title: t, version: "1"}
servers: [{url: "http://api.example.com"}]
paths:
  /x:
    get:
      responses: {"200": {description: ok}}
"""


def test_rules_endpoint_lists_openapi_rules(client: TestClient) -> None:
    ids = [r["id"] for r in client.get("/api/rules").json()]
    assert [i for i in ids if i.startswith("API-OAS-")] == [
        f"API-OAS-{n:03d}" for n in range(1, 11)
    ]


def test_analyze_openapi(client: TestClient) -> None:
    res = client.post("/api/analyze/openapi", json={"filename": "spec.yaml", "content": SPEC})
    assert res.status_code == 200
    body = res.json()
    assert body["generated_by"].startswith("Generated by Magen")
    assert body["operation_count"] == 1
    assert len(body["rules_run"]) == 10
    rule_ids = [f["rule_id"] for f in body["findings"]]
    assert rule_ids == ["API-OAS-001", "API-OAS-002", "API-OAS-003", "API-OAS-008"]
    assert body["findings"][0]["severity"] == "high"
    assert body["findings"][0]["evidence"][0]["location"] == {
        "file": "spec.yaml",
        "line": 3,
        "end_line": None,
        "pointer": "/servers/0/url",
        "url": None,
    }


def test_analyze_openapi_invalid_spec_uses_error_shape(client: TestClient) -> None:
    res = client.post(
        "/api/analyze/openapi", json={"filename": "s.yaml", "content": "swagger: '2.0'"}
    )
    assert res.status_code == 422
    assert res.json()["code"] == "invalid_openapi"
    assert "Swagger 2.0" in res.json()["message"]


def test_analyze_openapi_requires_token(anon_client: TestClient) -> None:
    res = anon_client.post("/api/analyze/openapi", json={"filename": "s.yaml", "content": SPEC})
    assert res.status_code == 401


def test_analyze_openapi_rejects_empty_content(client: TestClient) -> None:
    res = client.post("/api/analyze/openapi", json={"filename": "s.yaml", "content": ""})
    assert res.status_code == 422
    assert res.json()["code"] == "invalid_request"
